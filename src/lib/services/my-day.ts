export function parseApprovedNote(noteBody: string): {
  channel: string;
  contact: string;
  approvedMessage: string;
  sender: string | null;
} {
  const parts = noteBody.split(/\n\s*\n/);
  const header = parts[0] || "";
  const approvedMessage = parts.slice(1).join("\n\n").trim() || noteBody;

  let channel = "Manual";
  let contact = "";
  let sender: string | null = null;

  const senderMatch = header.match(/Sender\s+([^.]+)\./i);
  if (senderMatch) {
    sender = senderMatch[1].trim();
  }

  const channelMatch = header.match(/Channel\s+([^.\n]+)/i);
  if (channelMatch) {
    const rawChan = channelMatch[1].trim();
    if (/whatsapp/i.test(rawChan)) {
      channel = "WhatsApp";
      contact = rawChan.replace(/whatsapp/i, "").trim();
    } else if (/instagram/i.test(rawChan)) {
      channel = "Instagram";
      contact = rawChan.replace(/instagram\s+dm\s+to/i, "").replace(/instagram/i, "").trim();
    } else if (/email/i.test(rawChan)) {
      channel = "Email";
      contact = rawChan.replace(/email/i, "").trim();
    } else {
      channel = rawChan;
    }
  }

  return { channel, contact, approvedMessage, sender };
}

export function hasUsableContact(prospect: {
  handle: string;
  platform: string;
  phone: string | null;
  signalData?: Record<string, unknown>;
  isAutoGenerated?: boolean;
  approvedContact?: string | null;
  approvedChannel?: string | null;
}): { usable: boolean; channel: string; contact: string } {
  // 1. Structured approved contact
  if (prospect.approvedContact?.trim()) {
    return {
      usable: true,
      channel: prospect.approvedChannel?.trim() || "Approved contact",
      contact: prospect.approvedContact.trim(),
    };
  }

  // 2. Direct phone / WhatsApp
  if (prospect.phone?.trim()) {
    return {
      usable: true,
      channel: "Phone / WhatsApp",
      contact: prospect.phone.trim(),
    };
  }

  // 3. Public contact in signalData
  const publicContact = String(prospect.signalData?.public_contact ?? "").trim();
  if (publicContact) {
    const isWa = /whatsapp/i.test(publicContact);
    return {
      usable: true,
      channel: isWa ? "WhatsApp" : "Direct contact",
      contact: publicContact,
    };
  }

  // 4. Handle: if platform != 'manual' and not auto-generated
  const isAutoGenerated =
    prospect.isAutoGenerated ?? prospect.handle.startsWith("dec26-");
  if (prospect.platform !== "manual" && !isAutoGenerated && prospect.handle.trim()) {
    return {
      usable: true,
      channel: prospect.platform === "instagram" ? "Instagram" : prospect.platform,
      contact: `@${prospect.handle}`,
    };
  }

  return { usable: false, channel: prospect.platform, contact: "" };
}

// ── Follow-up threshold rule ─────────────────────────────────────────────────

export function isFollowUpDropped(attemptsCount: number): boolean {
  return attemptsCount >= 2;
}

// ── Week Bounds in Tenant Timezone ───────────────────────────────────────────

export function getWeekBounds(
  now = new Date(),
  timeZone = "Africa/Lagos"
): { weekStart: string; weekEnd: string } {
  const todayStr = getTenantToday(timeZone, now);
  const weekday = getIsoWeekday(todayStr); // 1 = Mon .. 7 = Sun
  const mondayStr = addDays(todayStr, 1 - weekday);
  const sundayStr = addDays(todayStr, 7 - weekday);

  const weekStart = getIsoDueAt(mondayStr, "00:00:00", timeZone);
  const weekEnd = getIsoDueAt(sundayStr, "23:59:59", timeZone);

  return { weekStart, weekEnd };
}

// ── Main My Day Data Fetcher ────────────────────────────────────────────────

export async function getMyDay(
  client: SupabaseClient,
  tenantSlug: string,
  options: {
    owner?: string;
    currentUserId?: string;
    nowMs?: number;
  } = {}
): Promise<MyDayData> {
  // 1. Resolve tenant timezone
  const { data: tenantRow } = await client
    .from("tenants")
    .select("timezone")
    .eq("slug", tenantSlug)
    .maybeSingle();

  const timeZone = (tenantRow?.timezone as string) || "Africa/Lagos";

  const now = options.nowMs ? new Date(options.nowMs) : new Date();
  const todayStr = getTenantToday(timeZone, now);
  const todayEndIso = getIsoDueAt(todayStr, "23:59:59", timeZone);
  const sevenDaysAgo = new Date(now.getTime() - 7 * 86400000).toISOString();
  const { weekStart, weekEnd } = getWeekBounds(now, timeZone);

  // 2. Fetch team roster from team_people
  const team = await listTeamMembers(client, tenantSlug, { activeOnly: false });
  const activeMembers = team.filter((m) => m.active);

  // 3. Determine owner filter type and person IDs
  const rawFilter = options.owner?.trim() || "all";
  let filterType: "all" | "unassigned" | "person" | "tag" = "all";
  let filterPersonId: string | null = null;
  let targetPersonIds: string[] = [];
  let filterLabel = "Everyone";

  if (rawFilter.toLowerCase() === "all" || rawFilter.toLowerCase() === "everyone") {
    filterType = "all";
    filterLabel = "Everyone";
  } else if (rawFilter.toLowerCase() === "unassigned") {
    filterType = "unassigned";
    filterLabel = "Unassigned";
  } else if (rawFilter.toLowerCase().startsWith("tag:")) {
    filterType = "tag";
    const tag = rawFilter.slice(4).toLowerCase();
    targetPersonIds = activeMembers
      .filter((m) => m.tags?.map((t) => t.toLowerCase()).includes(tag))
      .map((m) => m.id);
    filterLabel = `Tag: ${tag}`;
  } else {
    // Match by id or exact name
    const matched = team.find(
      (m) => m.id === rawFilter || m.name.toLowerCase() === rawFilter.toLowerCase()
    );
    if (matched) {
      filterType = "person";
      filterPersonId = matched.id;
      targetPersonIds = [matched.id];
      filterLabel = matched.name;
    } else if (rawFilter.toLowerCase() === "me" && options.currentUserId) {
      const myPerson = team.find((m) => m.userId === options.currentUserId);
      if (myPerson) {
        filterType = "person";
        filterPersonId = myPerson.id;
        targetPersonIds = [myPerson.id];
        filterLabel = myPerson.name;
      } else {
        filterType = "unassigned";
        filterLabel = "Unassigned";
      }
    } else {
      filterType = "person";
      filterPersonId = rawFilter;
      targetPersonIds = [rawFilter];
      filterLabel = rawFilter;
    }
  }

  // Helper to apply owner filter directly to queries in SQL (B2)
  interface FilterableQuery<T> {
    is: (column: string, value: null) => T;
    eq: (column: string, value: unknown) => T;
    in: (column: string, values: string[]) => T;
  }

  const applyOwnerFilter = <T extends FilterableQuery<T>>(
    query: T,
    column = "owner_person_id"
  ): T => {
    if (filterType === "all") return query;
    if (filterType === "unassigned") return query.is(column, null);
    if (filterType === "person" && filterPersonId) return query.eq(column, filterPersonId);
    if (filterType === "tag") {
      if (targetPersonIds.length === 0) return query.eq("id", "00000000-0000-0000-0000-000000000000");
      return query.in(column, targetPersonIds);
    }
    return query;
  };

  // 4. Build and execute queries in parallel
  // Inbound messages (uses prospects!inner join filter to avoid URL length explosion with >1000 IDs)
  let inboundSelect = "id, prospect_id, waiting_on_person_id, body, received_at, read_at";
  if (filterType !== "all") {
    inboundSelect += ", prospects!inner(id, owner_person_id)";
  }
  let inboundQuery = client
    .from("inbound_messages")
    .select(inboundSelect)
    .eq("tenant_slug", tenantSlug)
    .is("read_at", null)
    .order("received_at", { ascending: true })
    .limit(100);

  if (filterType === "person" && filterPersonId) {
    inboundQuery = inboundQuery.eq("prospects.owner_person_id", filterPersonId);
  } else if (filterType === "tag") {
    inboundQuery = targetPersonIds.length > 0
      ? inboundQuery.in("prospects.owner_person_id", targetPersonIds)
      : inboundQuery.eq("id", "00000000-0000-0000-0000-000000000000");
  } else if (filterType === "unassigned") {
    inboundQuery = inboundQuery.is("prospects.owner_person_id", null);
  }

  // Engagement items
  let engagementQuery = client
    .from("engagement_items")
    .select("id, prospect_id, owner_person_id, owner, waiting_on_person_id, from_handle, from_name, platform, body, content, why, received_at, status, proposed_reply, external_url")
    .eq("tenant_slug", tenantSlug)
    .in("status", ["open", "snoozed"])
    .order("received_at", { ascending: true })
    .limit(100);
  engagementQuery = applyOwnerFilter(engagementQuery);

  // Action items
  let actionQuery = client
    .from("action_items")
    .select("id, prospect_id, owner_person_id, owner, waiting_on_person_id, kind, title, body, why, priority, status, platform, external_url, due_at, created_at")
    .eq("tenant_slug", tenantSlug)
    .in("status", ["open", "snoozed"])
    .order("created_at", { ascending: true })
    .limit(150);
  actionQuery = applyOwnerFilter(actionQuery);

  // Approved prospects (ready to send vs find contact)
  let approvedProspectsQuery = client
    .from("prospects")
    .select("id, tenant_slug, handle, platform, status, priority, display_name, phone, signal_data, owner, owner_person_id, approved_message, approved_channel, approved_contact, is_auto_generated, last_reachout_at")
    .eq("tenant_slug", tenantSlug)
    .eq("status", "approved")
    .order("updated_at", { ascending: false })
    .limit(100);
  approvedProspectsQuery = applyOwnerFilter(approvedProspectsQuery);

  // Follow-ups due / overdue
  let followUpQuery = client
    .from("prospects")
    .select("id, tenant_slug, handle, platform, status, priority, display_name, owner, owner_person_id, follow_up_at, follow_up_note")
    .eq("tenant_slug", tenantSlug)
    .not("follow_up_at", "is", null)
    .lte("follow_up_at", todayEndIso)
    .not("status", "in", '("closed_won","closed_lost","dismissed","unqualified")')
    .order("follow_up_at", { ascending: true })
    .limit(100);
  followUpQuery = applyOwnerFilter(followUpQuery);

  // Sent prospects > 7 days
  let coldSentQuery = client
    .from("prospects")
    .select("id, tenant_slug, handle, platform, status, priority, display_name, owner, owner_person_id, last_reachout_at, last_touched_at, created_at, follow_up_at")
    .eq("tenant_slug", tenantSlug)
    .eq("status", "sent")
    .lt("last_reachout_at", sevenDaysAgo)
    .is("follow_up_at", null)
    .order("last_reachout_at", { ascending: true })
    .limit(100);
  coldSentQuery = applyOwnerFilter(coldSentQuery);

  // Find contact candidates (Priority A & B)
  let findContactQuery = client
    .from("prospects")
    .select("id, tenant_slug, handle, platform, status, priority, display_name, verified_name, event_title, phone, signal_data, owner, owner_person_id, is_auto_generated, created_at")
    .eq("tenant_slug", tenantSlug)
    .in("status", ["new", "qualified", "drafted", "approved"])
    .in("priority", ["A", "B"])
    .order("created_at", { ascending: false })
    .limit(100);
  findContactQuery = applyOwnerFilter(findContactQuery);

  // Scoreboard queries
  // 1. DMs sent this week (use sent_at per B1, inner join filter per owner)
  let dmsSelect = "id, prospect_id, sent_at, created_at";
  if (filterType !== "all") {
    dmsSelect += ", prospects!inner(id, owner_person_id)";
  }
  let dmsSentQuery = client
    .from("outbound_dms")
    .select(dmsSelect)
    .eq("tenant_slug", tenantSlug)
    .eq("status", "sent")
    .gte("sent_at", weekStart)
    .lte("sent_at", weekEnd);

  if (filterType === "person" && filterPersonId) {
    dmsSentQuery = dmsSentQuery.eq("prospects.owner_person_id", filterPersonId);
  } else if (filterType === "tag") {
    dmsSentQuery = targetPersonIds.length > 0
      ? dmsSentQuery.in("prospects.owner_person_id", targetPersonIds)
      : dmsSentQuery.eq("id", "00000000-0000-0000-0000-000000000000");
  } else if (filterType === "unassigned") {
    dmsSentQuery = dmsSentQuery.is("prospects.owner_person_id", null);
  }

  // 2. Replies received this week (inner join filter per owner)
  let inboundThisWeekSelect = "id, prospect_id, received_at";
  if (filterType !== "all") {
    inboundThisWeekSelect += ", prospects!inner(id, owner_person_id)";
  }
  let inboundThisWeekQuery = client
    .from("inbound_messages")
    .select(inboundThisWeekSelect)
    .eq("tenant_slug", tenantSlug)
    .gte("received_at", weekStart)
    .lte("received_at", weekEnd);

  if (filterType === "person" && filterPersonId) {
    inboundThisWeekQuery = inboundThisWeekQuery.eq("prospects.owner_person_id", filterPersonId);
  } else if (filterType === "tag") {
    inboundThisWeekQuery = targetPersonIds.length > 0
      ? inboundThisWeekQuery.in("prospects.owner_person_id", targetPersonIds)
      : inboundThisWeekQuery.eq("id", "00000000-0000-0000-0000-000000000000");
  } else if (filterType === "unassigned") {
    inboundThisWeekQuery = inboundThisWeekQuery.is("prospects.owner_person_id", null);
  }

  // 3. Calls booked (handed_off) using status_updated_at per B1
  let handedOffQuery = client
    .from("prospects")
    .select("id, owner_person_id, status_updated_at")
    .eq("tenant_slug", tenantSlug)
    .eq("status", "handed_off")
    .gte("status_updated_at", weekStart)
    .lte("status_updated_at", weekEnd);
  handedOffQuery = applyOwnerFilter(handedOffQuery);

  // 4. Events created (closed_won) using status_updated_at per B1
  let closedWonQuery = client
    .from("prospects")
    .select("id, owner_person_id, status_updated_at")
    .eq("tenant_slug", tenantSlug)
    .eq("status", "closed_won")
    .gte("status_updated_at", weekStart)
    .lte("status_updated_at", weekEnd);
  closedWonQuery = applyOwnerFilter(closedWonQuery);

  const [
    inboundRes,
    engagementRes,
    actionItemsRes,
    approvedProspectsRes,
    allFollowUpProspectsRes,
    coldSentProspectsRes,
    findContactCandidatesRes,
    dmsSentRes,
    inboundThisWeekRes,
    handedOffRes,
    closedWonRes,
  ] = await Promise.all([
    inboundQuery,
    engagementQuery,
    actionQuery,
    approvedProspectsQuery,
    followUpQuery,
    coldSentQuery,
    findContactQuery,
    dmsSentQuery,
    inboundThisWeekQuery,
    handedOffQuery,
    closedWonQuery,
  ]);

  // Collect needed prospect IDs for reply rows
  const inboundRows = (inboundRes.data ?? []) as unknown as InboundMessageRow[];
  const neededProspectIds = new Set<string>();
  for (const r of inboundRows) {
    if (r.prospect_id) neededProspectIds.add(r.prospect_id);
  }
  for (const e of engagementRes.data ?? []) {
    if (e.prospect_id) neededProspectIds.add(e.prospect_id);
  }
  for (const a of actionItemsRes.data ?? []) {
    if (a.prospect_id) neededProspectIds.add(a.prospect_id);
  }

  const prospectsMap = new Map<string, Record<string, unknown>>();
  if (neededProspectIds.size > 0) {
    const { data: pData } = await client
      .from("prospects")
      .select("id, tenant_slug, handle, platform, status, priority, display_name, phone, signal_data, owner, owner_person_id, approved_message, approved_channel, approved_contact, is_auto_generated")
      .in("id", Array.from(neededProspectIds));
    for (const p of pData ?? []) {
      prospectsMap.set(p.id, p);
    }
  }

  // Pre-fetch count of sent DMs per prospect for follow-up attempt counts
  const followUpProspectIds = [
    ...(allFollowUpProspectsRes.data ?? []).map((p) => p.id),
    ...(coldSentProspectsRes.data ?? []).map((p) => p.id),
  ];

  const attemptsCountMap = new Map<string, number>();
  if (followUpProspectIds.length > 0) {
    const { data: dms } = await client
      .from("outbound_dms")
      .select("prospect_id")
      .eq("tenant_slug", tenantSlug)
      .eq("status", "sent")
      .in("prospect_id", followUpProspectIds);

    for (const d of dms ?? []) {
      const pid = d.prospect_id as string;
      attemptsCountMap.set(pid, (attemptsCountMap.get(pid) || 0) + 1);
    }
  }

  const peopleMap = new Map<string, TeamMemberRecord>(team.map((m) => [m.id, m]));

  // ───────────────────────────────────────────────────────────────────────────
  // SECTION A: Reply now
  // ───────────────────────────────────────────────────────────────────────────
  const allReplyRows: ReplyNowItem[] = [];
  const seenReplyKeys = new Set<string>();

  // 1. From inbound_messages
  for (const msg of inboundRows) {
    const p = msg.prospect_id ? prospectsMap.get(msg.prospect_id) : null;
    const pOwner = (p?.owner as string | null) ?? null;
    const pOwnerPersonId = (p?.owner_person_id as string | null) ?? null;

    const receivedAt = msg.received_at;
    const daysWaited = Math.max(0, Math.floor((now.getTime() - new Date(receivedAt).getTime()) / 86400000));
    const handle = (p?.handle as string) ?? "unknown";
    const body = msg.body || "";

    const waitingPerson = msg.waiting_on_person_id ? peopleMap.get(msg.waiting_on_person_id) : null;
    const isWaitingOnPerson = !!waitingPerson;

    const key = `inbound-${msg.id}`;
    if (!seenReplyKeys.has(key)) {
      seenReplyKeys.add(key);
      allReplyRows.push({
        id: msg.id,
        source: "inbound_message",
        handle,
        displayName: (p?.display_name as string) ?? null,
        platform: (p?.platform as string) ?? "other",
        body,
        receivedAt,
        daysWaited,
        isUrgentWait: daysWaited >= 3,
        owner: pOwner,
        ownerPersonId: pOwnerPersonId,
        prospectId: msg.prospect_id,
        externalUrl: p ? `/leads?prospect=${p.id}` : null,
        proposedReply: null,
        isWaitingOnPerson,
        waitingOnPersonId: msg.waiting_on_person_id ?? null,
        waitingOnPersonName: waitingPerson?.name ?? null,
      });
    }
  }

  // 2. From engagement_items
  for (const eng of engagementRes.data ?? []) {
    const p = eng.prospect_id ? prospectsMap.get(eng.prospect_id) : null;
    const rowOwner = (eng.owner as string | null) ?? (p?.owner as string | null) ?? null;
    const rowOwnerPersonId = (eng.owner_person_id as string | null) ?? (p?.owner_person_id as string | null) ?? null;

    const receivedAt = eng.received_at;
    const daysWaited = Math.max(0, Math.floor((now.getTime() - new Date(receivedAt).getTime()) / 86400000));
    const body = (eng.body as string | null) ?? (eng.content as string) ?? "";

    const waitingPerson = eng.waiting_on_person_id ? peopleMap.get(eng.waiting_on_person_id) : null;
    const isWaitingOnPerson = !!waitingPerson;

    const key = `eng-${eng.id}`;
    if (!seenReplyKeys.has(key)) {
      seenReplyKeys.add(key);
      allReplyRows.push({
        id: eng.id,
        source: "engagement",
        handle: (eng.from_handle as string) ?? (p?.handle as string) ?? "unknown",
        displayName: (eng.from_name as string) ?? (p?.display_name as string) ?? null,
        platform: (eng.platform as string) ?? "instagram",
        body,
        receivedAt,
        daysWaited,
        isUrgentWait: daysWaited >= 3,
        owner: rowOwner,
        ownerPersonId: rowOwnerPersonId,
        prospectId: eng.prospect_id,
        externalUrl: eng.external_url ?? (p ? `/leads?prospect=${p.id}` : null),
        proposedReply: eng.proposed_reply,
        isWaitingOnPerson,
        waitingOnPersonId: eng.waiting_on_person_id ?? null,
        waitingOnPersonName: waitingPerson?.name ?? null,
      });
    }
  }

  // 3. From action_items kind='reply'
  for (const act of actionItemsRes.data ?? []) {
    if (act.kind !== "reply") continue;
    const p = act.prospect_id ? prospectsMap.get(act.prospect_id) : null;
    const rowOwner = (act.owner as string | null) ?? (p?.owner as string | null) ?? null;
    const rowOwnerPersonId = (act.owner_person_id as string | null) ?? (p?.owner_person_id as string | null) ?? null;

    const receivedAt = act.created_at;
    const daysWaited = Math.max(0, Math.floor((now.getTime() - new Date(receivedAt).getTime()) / 86400000));
    const body = (act.body as string | null) ?? act.title;

    const waitingPerson = act.waiting_on_person_id ? peopleMap.get(act.waiting_on_person_id) : null;
    const isWaitingOnPerson = !!waitingPerson;

    const key = `act-${act.id}`;
    if (!seenReplyKeys.has(key)) {
      seenReplyKeys.add(key);
      allReplyRows.push({
        id: act.id,
        source: "action",
        handle: (p?.handle as string) ?? act.title,
        displayName: (p?.display_name as string) ?? null,
        platform: (act.platform as string) ?? (p?.platform as string) ?? "other",
        body,
        receivedAt,
        daysWaited,
        isUrgentWait: daysWaited >= 3,
        owner: rowOwner,
        ownerPersonId: rowOwnerPersonId,
        prospectId: act.prospect_id,
        externalUrl: act.external_url ?? (p ? `/leads?prospect=${p.id}` : null),
        proposedReply: null,
        isWaitingOnPerson,
        waitingOnPersonId: act.waiting_on_person_id ?? null,
        waitingOnPersonName: waitingPerson?.name ?? null,
      });
    }
  }

  // Sort oldest first
  allReplyRows.sort((a, b) => new Date(a.receivedAt).getTime() - new Date(b.receivedAt).getTime());

  const replyNow = allReplyRows.filter((r) => !r.isWaitingOnPerson);
  const waitingOn = allReplyRows.filter((r) => r.isWaitingOnPerson);

  // ───────────────────────────────────────────────────────────────────────────
  // SECTION B & D: Ready to send vs Find the contact
  // ───────────────────────────────────────────────────────────────────────────
  const readyToSend: ReadyToSendItem[] = [];
  const findContactSet = new Map<string, FindContactItem>();

  for (const p of approvedProspectsRes.data ?? []) {
    const contactCheck = hasUsableContact({
      handle: p.handle,
      platform: p.platform,
      phone: p.phone,
      signalData: p.signal_data as Record<string, unknown>,
      isAutoGenerated: p.is_auto_generated,
      approvedContact: p.approved_contact,
      approvedChannel: p.approved_channel,
    });

    const priority = (p.priority as string | null) ?? "A";
    const owner = (p.owner as string | null) ?? null;
    const ownerPersonId = (p.owner_person_id as string | null) ?? null;

    if (contactCheck.usable) {
      readyToSend.push({
        id: p.id,
        name: (p.display_name as string) ?? p.handle,
        handle: p.handle,
        priority,
        owner,
        ownerPersonId,
        platform: p.platform,
        channel: contactCheck.channel,
        contact: contactCheck.contact,
        approvedMessage: (p.approved_message as string) ?? "",
        noteId: null,
        lastReachoutAt: p.last_reachout_at ?? null,
      });
    } else {
      findContactSet.set(p.id, {
        id: p.id,
        name: (p.display_name as string) ?? p.handle,
        handle: p.handle,
        priority,
        owner,
        ownerPersonId,
        platform: p.platform,
        sourceUrl: (p.signal_data as Record<string, unknown>)?.source_url as string | null,
        status: p.status,
      });
    }
  }

  // Priority candidates for section d
  for (const p of findContactCandidatesRes.data ?? []) {
    if (findContactSet.has(p.id)) continue;
    const contactCheck = hasUsableContact({
      handle: p.handle,
      platform: p.platform,
      phone: p.phone,
      signalData: p.signal_data as Record<string, unknown>,
      isAutoGenerated: p.is_auto_generated,
    });

    if (!contactCheck.usable) {
      const priority = (p.priority as string | null) ?? "A";
      const owner = (p.owner as string | null) ?? null;
      const ownerPersonId = (p.owner_person_id as string | null) ?? null;
      const name =
        (p.display_name as string) ??
        (p.verified_name as string) ??
        (p.event_title as string) ??
        p.handle;

      findContactSet.set(p.id, {
        id: p.id,
        name,
        handle: p.handle,
        priority,
        owner,
        ownerPersonId,
        platform: p.platform,
        sourceUrl: (p.signal_data as Record<string, unknown>)?.source_url as string | null,
        status: p.status,
      });
    }
  }

  const findContact = Array.from(findContactSet.values());

  // ───────────────────────────────────────────────────────────────────────────
  // SECTION C: Follow up today & Dropped follow-ups (B6)
  // ───────────────────────────────────────────────────────────────────────────
  const followUpToday: FollowUpTodayItem[] = [];
  const droppedFollowUps: FollowUpTodayItem[] = [];
  const seenFollowUpIds = new Set<string>();

  // 1. Scheduled follow-ups from prospects (overdue & due today)
  for (const p of allFollowUpProspectsRes.data ?? []) {
    const owner = (p.owner as string | null) ?? null;
    const ownerPersonId = (p.owner_person_id as string | null) ?? null;

    const dueAt = p.follow_up_at;
    const dueTime = dueAt ? new Date(dueAt).getTime() : now.getTime();
    const daysOverdue = Math.max(0, Math.floor((now.getTime() - dueTime) / 86400000));
    const attempts = attemptsCountMap.get(p.id) || 1;
    const dropped = isFollowUpDropped(attempts);

    seenFollowUpIds.add(p.id);
    const item: FollowUpTodayItem = {
      id: p.id,
      source: "prospect",
      name: (p.display_name as string) ?? p.handle,
      handle: p.handle,
      platform: p.platform,
      owner,
      ownerPersonId,
      daysOverdue,
      dueAt,
      suggestedNextStep: (p.follow_up_note as string) ?? "Send scheduled follow-up",
      attemptsCount: attempts,
      isFinalAttempt: attempts === 1,
      isDropped: dropped,
      prospectId: p.id,
      externalUrl: `/leads?prospect=${p.id}`,
    };

    if (dropped) {
      droppedFollowUps.push(item);
    } else {
      followUpToday.push(item);
    }
  }

  // 2. Sent prospects with no reply after 7 days
  for (const p of coldSentProspectsRes.data ?? []) {
    if (seenFollowUpIds.has(p.id)) continue;
    const owner = (p.owner as string | null) ?? null;
    const ownerPersonId = (p.owner_person_id as string | null) ?? null;

    const attempts = attemptsCountMap.get(p.id) || 1;
    const dropped = isFollowUpDropped(attempts);

    const lastTouched = p.last_reachout_at || p.last_touched_at || p.created_at;
    const daysOverdue = Math.max(0, Math.floor((now.getTime() - new Date(lastTouched).getTime()) / 86400000) - 7);

    seenFollowUpIds.add(p.id);
    const item: FollowUpTodayItem = {
      id: p.id,
      source: "prospect",
      name: (p.display_name as string) ?? p.handle,
      handle: p.handle,
      platform: p.platform,
      owner,
      ownerPersonId,
      daysOverdue,
      dueAt: lastTouched,
      suggestedNextStep: "No reply after 7 days · send final check-in",
      attemptsCount: attempts,
      isFinalAttempt: attempts === 1,
      isDropped: dropped,
      prospectId: p.id,
      externalUrl: `/leads?prospect=${p.id}`,
    };

    if (dropped) {
      droppedFollowUps.push(item);
    } else {
      followUpToday.push(item);
    }
  }

  // 3. Action queue items with kind='follow_up'
  for (const act of actionItemsRes.data ?? []) {
    if (act.kind !== "follow_up") continue;
    const p = act.prospect_id ? prospectsMap.get(act.prospect_id) : null;
    const rowOwner = (act.owner as string | null) ?? (p?.owner as string | null) ?? null;
    const rowOwnerPersonId = (act.owner_person_id as string | null) ?? (p?.owner_person_id as string | null) ?? null;

    const dueAt = act.due_at ?? act.created_at;
    const daysOverdue = dueAt ? Math.max(0, Math.floor((now.getTime() - new Date(dueAt).getTime()) / 86400000)) : 0;

    followUpToday.push({
      id: act.id,
      source: "action",
      name: act.title,
      handle: (p?.handle as string) ?? "follow_up",
      platform: (act.platform as string) ?? (p?.platform as string) ?? "other",
      owner: rowOwner,
      ownerPersonId: rowOwnerPersonId,
      daysOverdue,
      dueAt,
      suggestedNextStep: (act.why as string) ?? act.title,
      attemptsCount: 1,
      isFinalAttempt: false,
      isDropped: false,
      prospectId: act.prospect_id,
      externalUrl: act.external_url ?? (p ? `/leads?prospect=${p.id}` : null),
    });
  }

  followUpToday.sort((a, b) => b.daysOverdue - a.daysOverdue);
  droppedFollowUps.sort((a, b) => b.daysOverdue - a.daysOverdue);

  // ───────────────────────────────────────────────────────────────────────────
  // SECTION E: This week's scoreboard (B1)
  // ───────────────────────────────────────────────────────────────────────────
  const messagesSent = dmsSentRes.data?.length ?? 0;
  const repliesReceived = inboundThisWeekRes.data?.length ?? 0;
  const callsBooked = handedOffRes.data?.length ?? 0;
  const eventsCreated = closedWonRes.data?.length ?? 0;

  // Resolve targets: sum for Everyone or tag group, single person targets otherwise
  let targets: WeeklyTargets = {
    eventsCreated: 0,
    conversations: 0,
    reachOuts: 0,
    organicDms: 0,
  };

  if (filterType === "all") {
    for (const m of activeMembers) {
      targets.eventsCreated = (targets.eventsCreated || 0) + (m.weeklyTargets?.eventsCreated || 0);
      targets.conversations = (targets.conversations || 0) + (m.weeklyTargets?.conversations || 0);
      targets.reachOuts = (targets.reachOuts || 0) + (m.weeklyTargets?.reachOuts || 0);
      targets.organicDms = (targets.organicDms || 0) + (m.weeklyTargets?.organicDms || 0);
    }
  } else if (filterType === "tag") {
    const taggedMembers = activeMembers.filter((m) => targetPersonIds.includes(m.id));
    for (const m of taggedMembers) {
      targets.eventsCreated = (targets.eventsCreated || 0) + (m.weeklyTargets?.eventsCreated || 0);
      targets.conversations = (targets.conversations || 0) + (m.weeklyTargets?.conversations || 0);
      targets.reachOuts = (targets.reachOuts || 0) + (m.weeklyTargets?.reachOuts || 0);
      targets.organicDms = (targets.organicDms || 0) + (m.weeklyTargets?.organicDms || 0);
    }
  } else if (filterType === "person" && filterPersonId) {
    const person = peopleMap.get(filterPersonId);
    targets = person?.weeklyTargets ?? {
      eventsCreated: 0,
      conversations: 0,
      reachOuts: 0,
      organicDms: 0,
    };
  }

  const scoreboard: ScoreboardMetrics = {
    messagesSent,
    repliesReceived,
    callsBooked,
    eventsCreated,
    targets,
  };

  // ───────────────────────────────────────────────────────────────────────────
  // Summary line
  // ───────────────────────────────────────────────────────────────────────────
  const parts: string[] = [];
  if (replyNow.length > 0) parts.push(`${replyNow.length} repl${replyNow.length === 1 ? "y" : "ies"} waiting`);
  if (readyToSend.length > 0) parts.push(`${readyToSend.length} ready to send`);
  if (followUpToday.length > 0) parts.push(`${followUpToday.length} follow-up${followUpToday.length === 1 ? "" : "s"} due`);
  if (findContact.length > 0) parts.push(`${findContact.length} need a contact found`);

  const summary =
    parts.length > 0
      ? `${filterLabel}. ${parts.join(", ")}.`
      : `${filterLabel}. All caught up for today!`;

  return {
    owner: rawFilter,
    summary,
    replyNow,
    waitingOn,
    readyToSend,
    followUpToday,
    droppedFollowUps,
    findContact,
    scoreboard,
    team,
  };
}
