// ── Contact & Message Parsers ────────────────────────────────────────────────

export function parseApprovedNote(noteBody: string): {
  channel: string;
  contact: string;
  approvedMessage: string;
  sender: string | null;
} {
  const parts = noteBody.split(/\n\s*\n/);
  const header = parts[0] || "";
  const approvedMessage = parts.slice(1).join("\n\n").trim() || noteBody;

  let channel = "Manual";
  let contact = "";
  let sender: string | null = null;

  const senderMatch = header.match(/Sender\s+([^.]+)\./i);
  if (senderMatch) {
    sender = senderMatch[1].trim();
  }

  const channelMatch = header.match(/Channel\s+([^.\n]+)/i);
  if (channelMatch) {
    const rawChan = channelMatch[1].trim();
    if (/whatsapp/i.test(rawChan)) {
      channel = "WhatsApp";
      contact = rawChan.replace(/whatsapp/i, "").trim();
    } else if (/instagram/i.test(rawChan)) {
      channel = "Instagram";
      contact = rawChan.replace(/instagram\s+dm\s+to/i, "").replace(/instagram/i, "").trim();
    } else if (/email/i.test(rawChan)) {
      channel = "Email";
      contact = rawChan.replace(/email/i, "").trim();
    } else {
      channel = rawChan;
    }
  }

  return { channel, contact, approvedMessage, sender };
}

export function hasUsableContact(
  prospect: {
    handle: string;
    platform: string;
    phone: string | null;
    signalData: Record<string, unknown>;
  },
  approvedNote?: string | null
): { usable: boolean; channel: string; contact: string } {
  // 1. Check approved note
  if (approvedNote) {
    const parsed = parseApprovedNote(approvedNote);
    if (parsed.contact) {
      return { usable: true, channel: parsed.channel, contact: parsed.contact };
    }
  }

  // 2. Check public contact
  const publicContact = String(prospect.signalData?.public_contact ?? "").trim();
  if (publicContact) {
    const isWa = /whatsapp/i.test(publicContact);
    return {
      usable: true,
      channel: isWa ? "WhatsApp" : "Direct contact",
      contact: publicContact,
    };
  }

  // 3. Check phone
  if (prospect.phone?.trim()) {
    return {
      usable: true,
      channel: "Phone / WhatsApp",
      contact: prospect.phone.trim(),
    };
  }

  // 4. Check handle: if platform != 'manual' and handle does not start with dec26-
  const isAutoGenerated = prospect.handle.startsWith("dec26-");
  if (prospect.platform !== "manual" && !isAutoGenerated && prospect.handle.trim()) {
    return {
      usable: true,
      channel: prospect.platform === "instagram" ? "Instagram" : prospect.platform,
      contact: `@${prospect.handle}`,
    };
  }

  return { usable: false, channel: prospect.platform, contact: "" };
}

function matchesOwner(rowOwner: string | null | undefined, filterOwner: string): boolean {
  if (!filterOwner || filterOwner.toLowerCase() === "all" || filterOwner.toLowerCase() === "everyone") {
    return true;
  }
  if (!rowOwner) {
    return filterOwner.toLowerCase() === "unassigned";
  }

  const r = rowOwner.toLowerCase();
  const f = filterOwner.toLowerCase();
  if (r === f) return true;
  if (r.includes(f) || f.includes(r)) return true;

  // Handle "Ambassadors (via Abas)" mapping to Ambassador 1, Ambassador 2, or Abas
  if (r.includes("ambassador") && (f.includes("ambassador") || f === "abas")) return true;
  if (f.includes("ambassador") && r.includes("ambassador")) return true;

  return false;
}

// Helper to calculate start & end of current week (Monday 00:00:00 to Sunday 23:59:59)
export function getWeekBounds(now = new Date()): { weekStart: string; weekEnd: string } {
  const d = new Date(now);
  const day = d.getUTCDay(); // 0 is Sunday, 1 is Monday...
  const diffToMonday = (day === 0 ? -6 : 1) - day;
  const monday = new Date(Date.UTC(d.getUTCFullYear(), d.getUTCMonth(), d.getUTCDate() + diffToMonday, 0, 0, 0, 0));

  const sunday = new Date(Date.UTC(monday.getUTCFullYear(), monday.getUTCMonth(), monday.getUTCDate() + 6, 23, 59, 59, 999));

  return {
    weekStart: monday.toISOString(),
    weekEnd: sunday.toISOString(),
  };
}

// ── Main My Day Data Fetcher ────────────────────────────────────────────────

export async function getMyDay(
  client: SupabaseClient,
  tenantSlug: string,
  options: {
    owner?: string;
    currentUserId?: string;
    nowMs?: number;
  } = {}
): Promise<MyDayData> {
  const now = options.nowMs ? new Date(options.nowMs) : new Date();
  const todayEnd = new Date(now);
  todayEnd.setHours(23, 59, 59, 999);
  const todayEndIso = todayEnd.toISOString();
  const sevenDaysAgo = new Date(now.getTime() - 7 * 86400000).toISOString();
  const { weekStart, weekEnd } = getWeekBounds(now);

  const filterOwner = options.owner?.trim() || "all";

  // Run all primary queries in parallel
  const [
    team,
    inboundRes,
    engagementRes,
    actionItemsRes,
    approvedProspectsRes,
    allFollowUpProspectsRes,
    coldSentProspectsRes,
    findContactCandidatesRes,
    approvedNotesRes,
    dmsSentThisWeekRes,
    inboundThisWeekRes,
    handedOffThisWeekRes,
    closedWonThisWeekRes,
  ] = await Promise.all([
    listTeamMembers(client, tenantSlug),

    // 1. Inbound messages unread (Outbound Today replies)
    client
      .from("inbound_messages")
      .select("id, prospect_id, body, received_at, read_at")
      .eq("tenant_slug", tenantSlug)
      .is("read_at", null)
      .order("received_at", { ascending: true })
      .limit(100),

    // 2. Action queue engagement items (IG DMs/comments needing reply)
    client
      .from("engagement_items")
      .select("*")
      .eq("tenant_slug", tenantSlug)
      .in("status", ["open", "snoozed"])
      .order("received_at", { ascending: true })
      .limit(100),

    // 3. Action items (decisions, escalations, follow_up, chore)
    client
      .from("action_items")
      .select("*")
      .eq("tenant_slug", tenantSlug)
      .in("status", ["open", "snoozed"])
      .order("created_at", { ascending: true })
      .limit(150),

    // 4. Approved prospects (Section b & d)
    client
      .from("prospects")
      .select("*")
      .eq("tenant_slug", tenantSlug)
      .eq("status", "approved")
      .order("updated_at", { ascending: false })
      .limit(100),

    // 5. Prospects with scheduled follow-ups due or overdue
    client
      .from("prospects")
      .select("*")
      .eq("tenant_slug", tenantSlug)
      .not("follow_up_at", "is", null)
      .lte("follow_up_at", todayEndIso)
      .not("status", "in", "(closed_won,closed_lost,dismissed,unqualified)")
      .order("follow_up_at", { ascending: true })
      .limit(100),

    // 6. Sent prospects >7 days without follow_up_at scheduled
    client
      .from("prospects")
      .select("*")
      .eq("tenant_slug", tenantSlug)
      .eq("status", "sent")
      .lt("last_reachout_at", sevenDaysAgo)
      .is("follow_up_at", null)
      .order("last_reachout_at", { ascending: true })
      .limit(100),

    // 7. Priority A & B prospects for Section d ("Find the contact")
    client
      .from("prospects")
      .select("*")
      .eq("tenant_slug", tenantSlug)
      .in("status", ["new", "qualified", "drafted", "approved"])
      .or("priority.in.(A,B),signal_data->>priority.in.(A,B)")
      .order("created_at", { ascending: false })
      .limit(100),

    // 8. Approved notes starting with "First message, approved by Aise"
    client
      .from("prospect_notes")
      .select("id, prospect_id, body, created_at")
      .eq("tenant_slug", tenantSlug)
      .ilike("body", "First message, approved by Aise%")
      .order("created_at", { ascending: false })
      .limit(200),

    // 9. Scoreboard: DMs sent this week
    client
      .from("outbound_dms")
      .select("id, prospect_id, created_at, status")
      .eq("tenant_slug", tenantSlug)
      .eq("status", "sent")
      .gte("created_at", weekStart)
      .lte("created_at", weekEnd),

    // 10. Scoreboard: Inbound replies received this week
    client
      .from("inbound_messages")
      .select("id, prospect_id, received_at")
      .eq("tenant_slug", tenantSlug)
      .gte("received_at", weekStart)
      .lte("received_at", weekEnd),

    // 11. Scoreboard: Calls booked (handed_off) this week
    client
      .from("prospects")
      .select("id, owner, signal_data, updated_at")
      .eq("tenant_slug", tenantSlug)
      .eq("status", "handed_off")
      .gte("updated_at", weekStart)
      .lte("updated_at", weekEnd),

    // 12. Scoreboard: Events created (closed_won) this week
    client
      .from("prospects")
      .select("id, owner, signal_data, updated_at")
      .eq("tenant_slug", tenantSlug)
      .eq("status", "closed_won")
      .gte("updated_at", weekStart)
      .lte("updated_at", weekEnd),
  ]);

  // Index approved notes by prospect_id (latest first)
  const approvedNotesMap = new Map<string, { id: string; body: string }>();
  for (const n of approvedNotesRes.data ?? []) {
    if (!approvedNotesMap.has(n.prospect_id)) {
      approvedNotesMap.set(n.prospect_id, { id: n.id, body: n.body });
    }
  }

  // Collect all referenced prospect IDs to fetch their details in one batch
  const neededProspectIds = new Set<string>();
  for (const r of inboundRes.data ?? []) {
    if (r.prospect_id) neededProspectIds.add(r.prospect_id);
  }
  for (const e of engagementRes.data ?? []) {
    if (e.prospect_id) neededProspectIds.add(e.prospect_id);
  }
  for (const a of actionItemsRes.data ?? []) {
    if (a.prospect_id) neededProspectIds.add(a.prospect_id);
  }

  // Pre-load prospect rows if any needed
  const prospectsMap = new Map<string, Record<string, unknown>>();
  if (neededProspectIds.size > 0) {
    const { data: pData } = await client
      .from("prospects")
      .select("*")
      .in("id", Array.from(neededProspectIds));
    for (const p of pData ?? []) {
      prospectsMap.set(p.id, p);
    }
  }

  // Pre-fetch count of sent DMs per prospect for follow-up attempt counts
  const followUpProspectIds = [
    ...(allFollowUpProspectsRes.data ?? []).map((p) => p.id),
    ...(coldSentProspectsRes.data ?? []).map((p) => p.id),
  ];

  const attemptsCountMap = new Map<string, number>();
  if (followUpProspectIds.length > 0) {
    const { data: dms } = await client
      .from("outbound_dms")
      .select("prospect_id")
      .eq("tenant_slug", tenantSlug)
      .eq("status", "sent")
      .in("prospect_id", followUpProspectIds);

    for (const d of dms ?? []) {
      const pid = d.prospect_id as string;
      attemptsCountMap.set(pid, (attemptsCountMap.get(pid) || 0) + 1);
    }
  }

  // ───────────────────────────────────────────────────────────────────────────
  // SECTION A: Reply now
  // ───────────────────────────────────────────────────────────────────────────
  const allReplyRows: ReplyNowItem[] = [];
  const seenReplyKeys = new Set<string>();

  // 1. From inbound_messages
  for (const msg of inboundRes.data ?? []) {
    const p = msg.prospect_id ? prospectsMap.get(msg.prospect_id) : null;
    const pOwner = (p?.owner as string | null) ?? ((p?.signal_data as Record<string, unknown>)?.owner as string | null) ?? null;
    if (!matchesOwner(pOwner, filterOwner)) continue;

    const receivedAt = msg.received_at;
    const daysWaited = Math.max(0, Math.floor((now.getTime() - new Date(receivedAt).getTime()) / 86400000));
    const handle = (p?.handle as string) ?? "unknown";
    const body = msg.body || "";

    const isWaitingOnAise = !msg.read_at && /do not send/i.test(body);

    const key = `inbound-${msg.id}`;
    if (!seenReplyKeys.has(key)) {
      seenReplyKeys.add(key);
      allReplyRows.push({
        id: msg.id,
        source: "inbound_message",
        handle,
        displayName: (p?.display_name as string) ?? null,
        platform: (p?.platform as string) ?? "other",
        body,
        receivedAt,
        daysWaited,
        isUrgentWait: daysWaited >= 3,
        owner: pOwner,
        prospectId: msg.prospect_id,
        externalUrl: p ? `/leads?prospect=${p.id}` : null,
        proposedReply: null,
        isWaitingOnAise,
      });
    }
  }

  // 2. From engagement_items (comments/DMs needing reply)
  for (const eng of engagementRes.data ?? []) {
    if (eng.status === "resolved" || eng.status === "dismissed" || eng.status === "archived") continue;
    const p = eng.prospect_id ? prospectsMap.get(eng.prospect_id) : null;
    const rowOwner =
      (eng.owner as string | null) ??
      (p?.owner as string | null) ??
      ((p?.signal_data as Record<string, unknown>)?.owner as string | null) ??
      null;

    if (!matchesOwner(rowOwner, filterOwner)) continue;

    const receivedAt = eng.received_at;
    const daysWaited = Math.max(0, Math.floor((now.getTime() - new Date(receivedAt).getTime()) / 86400000));
    const body = (eng.body as string | null) ?? (eng.content as string) ?? "";
    const noteText = `${eng.why ?? ""} ${body}`;
    const isWaitingOnAise = !eng.proposed_reply && /do not send/i.test(noteText);

    const key = `eng-${eng.id}`;
    if (!seenReplyKeys.has(key)) {
      seenReplyKeys.add(key);
      allReplyRows.push({
        id: eng.id,
        source: "engagement",
        handle: (eng.from_handle as string) ?? (p?.handle as string) ?? "unknown",
        displayName: (eng.from_name as string) ?? (p?.display_name as string) ?? null,
        platform: (eng.platform as string) ?? "instagram",
        body,
        receivedAt,
        daysWaited,
        isUrgentWait: daysWaited >= 3,
        owner: rowOwner,
        prospectId: eng.prospect_id,
        externalUrl: eng.external_url ?? (p ? `/leads?prospect=${p.id}` : null),
        proposedReply: eng.proposed_reply,
        isWaitingOnAise,
      });
    }
  }

  // 3. From action_items kind='reply'
  for (const act of actionItemsRes.data ?? []) {
    if (act.kind !== "reply") continue;
    if (act.status === "resolved" || act.status === "dismissed" || act.status === "archived") continue;
    const p = act.prospect_id ? prospectsMap.get(act.prospect_id) : null;
    const rowOwner =
      (act.owner as string | null) ??
      (p?.owner as string | null) ??
      ((p?.signal_data as Record<string, unknown>)?.owner as string | null) ??
      null;

    if (!matchesOwner(rowOwner, filterOwner)) continue;

    const receivedAt = act.created_at;
    const daysWaited = Math.max(0, Math.floor((now.getTime() - new Date(receivedAt).getTime()) / 86400000));
    const body = (act.body as string | null) ?? act.title;
    const noteText = `${act.why ?? ""} ${body}`;
    const isWaitingOnAise = !act.proposed_reply && /do not send/i.test(noteText);

    const key = `act-${act.id}`;
    if (!seenReplyKeys.has(key)) {
      seenReplyKeys.add(key);
      allReplyRows.push({
        id: act.id,
        source: "action",
        handle: (p?.handle as string) ?? act.title,
        displayName: (p?.display_name as string) ?? null,
        platform: (act.platform as string) ?? (p?.platform as string) ?? "other",
        body,
        receivedAt,
        daysWaited,
        isUrgentWait: daysWaited >= 3,
        owner: rowOwner,
        prospectId: act.prospect_id,
        externalUrl: act.external_url ?? (p ? `/leads?prospect=${p.id}` : null),
        proposedReply: act.proposed_reply,
        isWaitingOnAise,
      });
    }
  }

  // Sort oldest first
  allReplyRows.sort((a, b) => new Date(a.receivedAt).getTime() - new Date(b.receivedAt).getTime());

  const replyNow = allReplyRows.filter((r) => !r.isWaitingOnAise);
  const waitingOnAise = allReplyRows.filter((r) => r.isWaitingOnAise);

  // ───────────────────────────────────────────────────────────────────────────
  // SECTION B & D: Ready to send vs Find the contact
  // ───────────────────────────────────────────────────────────────────────────
  const readyToSend: ReadyToSendItem[] = [];
  const findContactSet = new Map<string, FindContactItem>();

  for (const p of approvedProspectsRes.data ?? []) {
    const owner = (p.owner as string | null) ?? ((p.signal_data as Record<string, unknown>)?.owner as string | null) ?? null;
    if (!matchesOwner(owner, filterOwner)) continue;

    const approvedNoteObj = approvedNotesMap.get(p.id);
    const approvedNote = approvedNoteObj?.body ?? null;
    const contactCheck = hasUsableContact(
      {
        handle: p.handle,
        platform: p.platform,
        phone: p.phone,
        signalData: (p.signal_data as Record<string, unknown>) ?? {},
      },
      approvedNote
    );

    const priority =
      (p.priority as string | null) ??
      ((p.signal_data as Record<string, unknown>)?.priority as string | null) ??
      "A";

    const name =
      (p.display_name as string) ??
      (p.verified_name as string) ??
      (p.event_title as string) ??
      p.handle;

    if (!contactCheck.usable) {
      // Move to Section d
      findContactSet.set(p.id, {
        id: p.id,
        name,
        handle: p.handle,
        priority,
        owner,
        platform: p.platform,
        sourceUrl: (p.signal_data as Record<string, unknown>)?.source_url as string | null,
        status: p.status,
      });
    } else {
      const parsedNote = approvedNote ? parseApprovedNote(approvedNote) : null;
      readyToSend.push({
        id: p.id,
        name,
        handle: p.handle,
        priority,
        owner,
        platform: p.platform,
        channel: contactCheck.channel,
        contact: contactCheck.contact,
        approvedMessage: parsedNote?.approvedMessage ?? "Ready for outreach",
        noteId: approvedNoteObj?.id ?? null,
        lastReachoutAt: p.last_reachout_at,
      });
    }
  }

  // Also include other priority A & B prospects with no usable contact in Section d
  for (const p of findContactCandidatesRes.data ?? []) {
    if (findContactSet.has(p.id)) continue;
    const owner = (p.owner as string | null) ?? ((p.signal_data as Record<string, unknown>)?.owner as string | null) ?? null;
    if (!matchesOwner(owner, filterOwner)) continue;

    const contactCheck = hasUsableContact({
      handle: p.handle,
      platform: p.platform,
      phone: p.phone,
      signalData: (p.signal_data as Record<string, unknown>) ?? {},
    });

    if (!contactCheck.usable) {
      const priority =
        (p.priority as string | null) ??
        ((p.signal_data as Record<string, unknown>)?.priority as string | null) ??
        "A";
      const name =
        (p.display_name as string) ??
        (p.verified_name as string) ??
        (p.event_title as string) ??
        p.handle;

      findContactSet.set(p.id, {
        id: p.id,
        name,
        handle: p.handle,
        priority,
        owner,
        platform: p.platform,
        sourceUrl: (p.signal_data as Record<string, unknown>)?.source_url as string | null,
        status: p.status,
      });
    }
  }

  const findContact = Array.from(findContactSet.values());

  // ───────────────────────────────────────────────────────────────────────────
  // SECTION C: Follow up today
  // ───────────────────────────────────────────────────────────────────────────
  const followUpToday: FollowUpTodayItem[] = [];
  const seenFollowUpIds = new Set<string>();

  // 1. Scheduled follow-ups from prospects (overdue & due today)
  for (const p of allFollowUpProspectsRes.data ?? []) {
    const owner = (p.owner as string | null) ?? ((p.signal_data as Record<string, unknown>)?.owner as string | null) ?? null;
    if (!matchesOwner(owner, filterOwner)) continue;

    const dueAt = p.follow_up_at;
    const dueTime = dueAt ? new Date(dueAt).getTime() : now.getTime();
    const daysOverdue = Math.max(0, Math.floor((now.getTime() - dueTime) / 86400000));
    const attempts = attemptsCountMap.get(p.id) || 1;

    // Respect rule: lead dropped after 2 unanswered attempts
    if (attempts > 2) continue;

    seenFollowUpIds.add(p.id);
    followUpToday.push({
      id: p.id,
      source: "prospect",
      name: (p.display_name as string) ?? p.handle,
      handle: p.handle,
      platform: p.platform,
      owner,
      daysOverdue,
      dueAt,
      suggestedNextStep: (p.follow_up_note as string) ?? "Send scheduled follow-up",
      attemptsCount: attempts,
      isFinalAttempt: attempts === 2,
      prospectId: p.id,
      externalUrl: `/leads?prospect=${p.id}`,
    });
  }

  // 2. Sent prospects with no reply after 7 days that have had < 2 attempts
  for (const p of coldSentProspectsRes.data ?? []) {
    if (seenFollowUpIds.has(p.id)) continue;
    const owner = (p.owner as string | null) ?? ((p.signal_data as Record<string, unknown>)?.owner as string | null) ?? null;
    if (!matchesOwner(owner, filterOwner)) continue;

    const attempts = attemptsCountMap.get(p.id) || 1;
    if (attempts >= 2) continue; // Dropped after 2 unanswered attempts

    const lastTouched = p.last_reachout_at || p.last_touched_at || p.created_at;
    const daysOverdue = Math.max(0, Math.floor((now.getTime() - new Date(lastTouched).getTime()) / 86400000) - 7);

    seenFollowUpIds.add(p.id);
    followUpToday.push({
      id: p.id,
      source: "prospect",
      name: (p.display_name as string) ?? p.handle,
      handle: p.handle,
      platform: p.platform,
      owner,
      daysOverdue,
      dueAt: lastTouched,
      suggestedNextStep: "No reply after 7 days · send final check-in",
      attemptsCount: attempts,
      isFinalAttempt: attempts === 1, // Next attempt is attempt 2
      prospectId: p.id,
      externalUrl: `/leads?prospect=${p.id}`,
    });
  }

  // 3. Action queue items with kind='follow_up'
  for (const act of actionItemsRes.data ?? []) {
    if (act.kind !== "follow_up") continue;
    if (act.status === "resolved" || act.status === "dismissed" || act.status === "archived") continue;
    const p = act.prospect_id ? prospectsMap.get(act.prospect_id) : null;
    const rowOwner =
      (act.owner as string | null) ??
      (p?.owner as string | null) ??
      ((p?.signal_data as Record<string, unknown>)?.owner as string | null) ??
      null;

    if (!matchesOwner(rowOwner, filterOwner)) continue;

    const dueAt = act.due_at ?? act.created_at;
    const daysOverdue = dueAt ? Math.max(0, Math.floor((now.getTime() - new Date(dueAt).getTime()) / 86400000)) : 0;

    followUpToday.push({
      id: act.id,
      source: "action",
      name: act.title,
      handle: (p?.handle as string) ?? "follow_up",
      platform: (act.platform as string) ?? (p?.platform as string) ?? "other",
      owner: rowOwner,
      daysOverdue,
      dueAt,
      suggestedNextStep: (act.why as string) ?? act.title,
      attemptsCount: 1,
      isFinalAttempt: false,
      prospectId: act.prospect_id,
      externalUrl: act.external_url ?? (p ? `/leads?prospect=${p.id}` : null),
    });
  }

  // Sort by days overdue descending (most overdue first)
  followUpToday.sort((a, b) => b.daysOverdue - a.daysOverdue);

  // ───────────────────────────────────────────────────────────────────────────
  // SECTION E: This week's scoreboard
  // ───────────────────────────────────────────────────────────────────────────
  let messagesSent = 0;
  for (const dm of dmsSentThisWeekRes.data ?? []) {
    const p = dm.prospect_id ? prospectsMap.get(dm.prospect_id) : null;
    const owner = (p?.owner as string | null) ?? ((p?.signal_data as Record<string, unknown>)?.owner as string | null);
    if (matchesOwner(owner, filterOwner)) {
      messagesSent++;
    }
  }

  let repliesReceived = 0;
  for (const inMsg of inboundThisWeekRes.data ?? []) {
    const p = inMsg.prospect_id ? prospectsMap.get(inMsg.prospect_id) : null;
    const owner = (p?.owner as string | null) ?? ((p?.signal_data as Record<string, unknown>)?.owner as string | null);
    if (matchesOwner(owner, filterOwner)) {
      repliesReceived++;
    }
  }

  let callsBooked = 0;
  for (const p of handedOffThisWeekRes.data ?? []) {
    const owner = (p.owner as string | null) ?? ((p.signal_data as Record<string, unknown>)?.owner as string | null);
    if (matchesOwner(owner, filterOwner)) {
      callsBooked++;
    }
  }

  let eventsCreated = 0;
  for (const p of closedWonThisWeekRes.data ?? []) {
    const owner = (p.owner as string | null) ?? ((p.signal_data as Record<string, unknown>)?.owner as string | null);
    if (matchesOwner(owner, filterOwner)) {
      eventsCreated++;
    }
  }

  // Resolve targets for the selected person or sum for everyone
  const targetMember = team.find((m) => matchesOwner(m.name, filterOwner));
  const defaultTargets = targetMember?.weeklyTargets ?? {
    eventsCreated: 25,
    conversations: 40,
    reachOuts: 100,
    organicDms: 20,
  };

  const scoreboard: ScoreboardMetrics = {
    messagesSent,
    repliesReceived,
    callsBooked,
    eventsCreated,
    targets: defaultTargets,
  };

  // ───────────────────────────────────────────────────────────────────────────
  // Summary line
  // ───────────────────────────────────────────────────────────────────────────
  const personLabel = filterOwner.toLowerCase() === "all" ? "Everyone" : filterOwner;
  const parts: string[] = [];
  if (replyNow.length > 0) parts.push(`${replyNow.length} repl${replyNow.length === 1 ? "y" : "ies"} waiting`);
  if (readyToSend.length > 0) parts.push(`${readyToSend.length} ready to send`);
  if (followUpToday.length > 0) parts.push(`${followUpToday.length} follow-up${followUpToday.length === 1 ? "" : "s"} due`);
  if (findContact.length > 0) parts.push(`${findContact.length} need a contact found`);

  const summary = parts.length > 0
    ? `${personLabel}. ${parts.join(", ")}.`
    : `${personLabel}. All caught up for today!`;

  return {
    owner: filterOwner,
    summary,
    replyNow,
    waitingOnAise,
    readyToSend,
    followUpToday,
    findContact,
    scoreboard,
    team,
  };
}
